# pypinyin 个别多音字/轻声的修正表（按部编版词语表核对）
OVERRIDE = {
    "热闹": "rè nao",      # 闹 轻声
    "漂亮": "piào liang",  # 亮 轻声
    "妥当": "tuǒ dang",    # 当 轻声
    "葫芦": "hú lu",       # 芦 轻声
    "指甲": "zhǐ jia",     # 甲 轻声
    "衣服": "yī fu",       # 服 轻声
    "要是": "yào shi",     # 是 轻声
    "答应": "dā ying",     # 应 轻声
    "仙子": "xiān zǐ",     # 子非词缀，读 zǐ
    "散发": "sàn fā",      # 发 fā 一声
}


def to_pinyin(word):
    if word in OVERRIDE:
        return OVERRIDE[word]
    return ' '.join(p[0] for p in pinyin(word, style=Style.TONE))


new_data = []
num = 0
for unit, words in DATA:
    num += 1
    for w in words:
        new_data.append({
            "unit": unit, "unitNum": num,
            "word": w, "pinyin": to_pinyin(w),
        })

with open('cn_words.json', 'r', encoding='utf-8') as f:
    old = json.load(f)
old_words = {x['word'] for v in old.values() for x in v}

with open('cn_words.json', 'w', encoding='utf-8') as f:
    json.dump({"三年级上册": new_data, "三年级下册": []}, f, ensure_ascii=False, indent=1)

print('语文重建完成：', len(new_data), '词，', len(DATA), '组')
print('旧词表', len(old_words), '词 → 新词表', len({x["word"] for x in new_data}), '个不同词')
